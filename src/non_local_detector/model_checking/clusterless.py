def interval_rescaling_transform(
    time: np.ndarray,
    spike_times: np.ndarray,
    spike_waveform_features: np.ndarray,
    ground_process_intensity: np.ndarray,
    conditional_mark_cdf: Callable[
        [np.ndarray, np.ndarray, Sequence[int] | None], ArrayLike
    ],
    *,
    feature_order: Sequence[int] | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """IRCM transform from a sampled ground intensity and a conditional mark CDF.

    The general form of :func:`ircm_transform`, for marked point process
    models other than the fitted clusterless encoding models.

    Parameters
    ----------
    time : np.ndarray, shape (n_time,)
        Strictly increasing sample times in seconds of the ground intensity.
        The first interval starts at ``time[0]``.
    spike_times : np.ndarray, shape (n_spikes,)
        Ordered spike times within ``time``.
    spike_waveform_features : np.ndarray, shape (n_spikes, n_features)
        The spikes' marks.
    ground_process_intensity : np.ndarray, shape (n_time,)
        Ground intensity in Hz at ``time``, integrated as a piecewise-linear
        function of time.
    conditional_mark_cdf : callable
        ``conditional_mark_cdf(spike_times, marks, feature_order)`` returns the
        sequential conditional CDFs of the marks given the spike time, shape
        ``(n_spikes, n_features)``, column ``l`` for feature
        ``feature_order[l]`` (identity when None).
        :class:`GaussianMixtureConditionalCDF` instances qualify.
    feature_order : sequence of int, optional
        The order in which mark features are conditioned.

    Returns
    -------
    u : np.ndarray, shape (n_spikes,)
        Rescaled interspike intervals.
    v : np.ndarray, shape (n_spikes, n_features)
        Conditional CDFs of the marks.
    """
    ground_at_spikes = np.interp(spike_times, time, ground_process_intensity)
    if not np.all(np.isfinite(ground_at_spikes) & (ground_at_spikes > 0)):
        raise ValueError(
            "ground_process_intensity is zero or invalid at some spike times, "
            "so the model gives those spikes no probability"
        )
    marks = np.asarray(spike_waveform_features, dtype=float)
    if marks.ndim != 2 or marks.shape[0] != len(spike_times):
        raise ValueError(
            "spike_waveform_features must be an (n_spikes, n_features) matrix"
        )
    u = scipy.stats.expon.cdf(
        _compute_rescaled_isi(ground_process_intensity, spike_times, time)
    )
    v = np.asarray(
        conditional_mark_cdf(np.asarray(spike_times), marks, feature_order),
        dtype=np.float64,
    )
    if v.shape != marks.shape or not np.all(np.isfinite(v) & (v >= 0) & (v <= 1)):
        raise ValueError(
            "conditional_mark_cdf must return finite values in [0, 1], one per "
            "spike and feature"
        )
    return u, v


def _compute_rescaled_isi(
    intensity: np.ndarray,
    spike_times: np.ndarray,
    time: np.ndarray,
) -> np.ndarray:
    """Compute the rescaled interspike intervals for a single electrode.

    Parameters
    ----------
    intensity : np.ndarray, shape (n_time,)
        Ground process rates in Hz.
    spike_times : np.ndarray, shape (n_spikes,)
        Times at which spikes occurred.
    time : np.ndarray, shape (n_time,)
        Strictly increasing sample times in seconds. The first rescaled ISI
        begins at the first sample, not at an inferred acquisition boundary.

    Returns
    -------
    rescaled_isi : np.ndarray, shape (n_spikes,)
        Rescaled interspike intervals computed by integrating the intensity
        function between consecutive spike times.
    """
    # Promote rates before quadrature and rate differences: integer
    # arithmetic can wrap and finite float32 rates can overflow when added.
    intensity = np.asarray(intensity, dtype=float)
    time = np.asarray(time, dtype=float)
    spike_times = np.asarray(spike_times, dtype=float)
    if intensity.ndim != 1 or not intensity.size or time.shape != intensity.shape:
        raise ValueError(
            "time and intensity must have matching nonempty one-dimensional rows"
        )
    with np.errstate(over="ignore", invalid="ignore"):
        durations = np.diff(time)
    if (
        not np.all(np.isfinite(time))
        or not np.all(np.isfinite(durations))
        or np.any(durations <= 0)
    ):
        raise ValueError("time must be finite and strictly increasing")
    if (
        spike_times.ndim != 1
        or not np.all(np.isfinite(spike_times))
        or np.any(np.diff(spike_times) < 0)
    ):
        raise ValueError("spike_times must be finite, one-dimensional, and ordered")
    if np.any((spike_times < time[0]) | (spike_times > time[-1])):
        raise ValueError("spike_times must lie within the intensity sample time range")
    if not np.all(np.isfinite(intensity)) or np.any(intensity < 0):
        raise ValueError(
            "ground_process_intensity must be finite and nonnegative; "
            "non-finite or <= 0 values at spike times are invalid"
        )
    if len(time) == 1:
        ici_at_spike = np.zeros_like(spike_times)
    else:
        integrated = scipy.integrate.cumulative_trapezoid(
            intensity, x=time, initial=0.0
        )
        left = np.clip(
            np.searchsorted(time, spike_times, side="right") - 1, 0, len(time) - 2
        )
        elapsed = spike_times - time[left]
        fraction = elapsed / durations[left]
        # Integrate the linear rate without squaring elapsed time or forming
        # a slope that can overflow for a very short, otherwise valid cell.
        ici_at_spike = integrated[left] + elapsed * (
            intensity[left] + 0.5 * fraction * (intensity[left + 1] - intensity[left])
        )
    ici_at_spike = np.concatenate((np.array([0]), ici_at_spike))
    return np.diff(ici_at_spike)


def _prepare_inputs(
    encoding_model, position_time, position, spike_times, spike_waveform_features
):
    """Validated sample times, positions, spike times and marks."""
    time = np.asarray(position_time, dtype=float)
    if time.ndim != 1 or time.size < 2 or not np.all(np.diff(time) > 0):
        raise ValueError(
            "position_time must be one-dimensional, strictly increasing and have "
            "at least two samples"
        )
    spike_times = np.asarray(spike_times, dtype=float)
    if (
        spike_times.ndim != 1
        or not np.all(np.isfinite(spike_times))
        or np.any(np.diff(spike_times) < 0)
        or np.any((spike_times < time[0]) | (spike_times > time[-1]))
    ):
        raise ValueError(
            "spike_times must be finite, ordered and within the position_time range"
        )
    marks = np.asarray(spike_waveform_features, dtype=float)
    if (
        marks.ndim != 2
        or marks.shape[0] != spike_times.size
        or not np.isfinite(marks).all()
    ):
        raise ValueError(
            "spike_waveform_features must be a finite (n_spikes, n_features) matrix"
        )
    environment = encoding_model["environment"]
    positions = np.asarray(
        get_position_at_time(time, position, time, environment), dtype=float
    )
    spike_positions = np.asarray(
        get_position_at_time(time, position, spike_times, environment), dtype=float
    )
    if not (np.isfinite(positions).all() and np.isfinite(spike_positions).all()):
        raise ValueError(
            "position must be finite at every position_time sample; split the "
            "period at tracking gaps"
        )
    if positions.ndim == 1:
        positions, spike_positions = positions[:, None], spike_positions[:, None]
    return time, positions, spike_times, spike_positions, marks


def _check_algorithm(algorithm):
    if algorithm not in SUPPORTED_ALGORITHMS:
        raise ValueError(
            f"algorithm must be one of {SUPPORTED_ALGORITHMS}, got {algorithm!r}"
        )


def ircm_transform(
    encoding_model: dict,
    algorithm: str,
    electrode: int,
    position_time: np.ndarray,
    position: np.ndarray,
    spike_times: np.ndarray,
    spike_waveform_features: np.ndarray,
    *,
    feature_order: Sequence[int] | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Interval-rescaling conditional mark distribution (IRCM) transform [1]_.

    Each interspike interval is rescaled by the electrode's ground intensity
    along the animal's trajectory,

        u_i = 1 - exp(-integral_{s_(i-1)}^{s_i} Lambda(x(t)) dt),

    with ``s_0 = position_time[0]``, and each spike's marks by the sequential
    (Rosenblatt) CDFs of the model's conditional mark density at the spike's
    position, ``f(m | x) = lambda(x, m) / Lambda(x)``:

        v_i^(l) = F(m_i^(l) | m_i^(1), ..., m_i^(l-1), x(s_i)).

    For spikes generated by the model the points ``(u_i, v_i)`` are
    independent and uniform on ``[0, 1]^(d+1)``. Non-uniform ``u`` points to the
    temporal (rate) model; non-uniform ``v^(l)`` with uniform earlier columns
    points to the model of mark feature ``l``.

    Parameters
    ----------
    encoding_model : dict
        A fitted clusterless encoding model, as stored in a detector's
        ``encoding_model_``.
    algorithm : str
        The algorithm that fitted it: ``"clusterless_kde"``,
        ``"clusterless_kde_log"``, ``"clusterless_gmm"`` or
        ``"clusterless_diffusion"``.
    electrode : int
        Index of the electrode in the encoding model.
    position_time : np.ndarray, shape (n_time,)
        Strictly increasing sample times in seconds of the evaluated period.
    position : np.ndarray, shape (n_time,) or (n_time, n_position_dims)
        The animal's position at ``position_time``, finite at every sample.
        It is interpolated and linearized for track graphs as during fitting.
        Split the period at tracking gaps.
    spike_times : np.ndarray, shape (n_spikes,)
        Ordered spike times of the electrode within ``position_time``.
    spike_waveform_features : np.ndarray, shape (n_spikes, n_features)
        The spikes' marks.
    feature_order : sequence of int, optional
        The order in which mark features are conditioned; identity by default.
        Any order gives uniform points for the correct model.

    Returns
    -------
    u : np.ndarray, shape (n_spikes,)
        Rescaled interspike intervals.
    v : np.ndarray, shape (n_spikes, n_features)
        Column ``l`` is the conditional CDF of feature ``feature_order[l]``.

    Notes
    -----
    The ground intensity is evaluated at the position samples and integrated
    as a piecewise-linear function of time. For clusterless diffusion the
    model, and so ``Lambda`` and ``f(m | x)``, is defined on the interior bins
    and read at the bin containing the position.
    """
    _check_algorithm(algorithm)
    time, positions, spike_times, spike_positions, marks = _prepare_inputs(
        encoding_model, position_time, position, spike_times, spike_waveform_features
    )
    model = electrode_model(encoding_model, algorithm, electrode)
    ground = model.ground_intensity(positions)
    ground_at_spikes = model.ground_intensity(spike_positions)
    if not np.all(np.isfinite(ground_at_spikes) & (ground_at_spikes > 0)):
        raise ValueError(
            "the fitted ground intensity is zero or invalid at some spike "
            "positions, so the model gives those spikes no probability"
        )
    u = scipy.stats.expon.cdf(_compute_rescaled_isi(ground, spike_times, time))
    v = model.conditional_mark_cdf(spike_positions, marks, feature_order)
    return u, v


def _time_in_bins(sample_times, sample_bins, n_bins, query_times):
    """Seconds the trajectory spends in each bin before each query time.

    As for the ground intensity, the integrand is interpolated linearly
    between samples: an interval gives half its duration to each endpoint's
    bin, and a query inside an interval receives the exact integral of the
    two interpolation weights up to the query.

    Parameters
    ----------
    sample_times : np.ndarray, shape (n_time,)
    sample_bins : np.ndarray, shape (n_time,)
        Bin of the position at each sample.
    n_bins : int
    query_times : np.ndarray, shape (n_queries,)
        Ordered times within ``sample_times``.

    Returns
    -------
    time_in_bins : np.ndarray, shape (n_queries, n_bins)
    """
    durations = np.diff(sample_times)
    interval = np.clip(
        np.searchsorted(sample_times, query_times, side="right") - 1,
        0,
        len(durations) - 1,
    )
    left, right = sample_bins[:-1], sample_bins[1:]
    # Interval j counts in full for every query whose own interval is later.
    first_query = np.searchsorted(interval, np.arange(len(durations)), side="right")
    window = np.zeros((len(query_times) + 1, n_bins))
    np.add.at(window, (first_query, left), 0.5 * durations)
    np.add.at(window, (first_query, right), 0.5 * durations)
    cumulative = np.cumsum(window, axis=0)[:-1]
    elapsed = query_times - sample_times[interval]
    to_right = 0.5 * elapsed * elapsed / durations[interval]
    rows = np.arange(len(query_times))
    np.add.at(cumulative, (rows, left[interval]), elapsed - to_right)
    np.add.at(cumulative, (rows, right[interval]), to_right)
    return cumulative


def mdci_transform(
    encoding_model: dict,
    algorithm: str,
    electrode: int,
    position_time: np.ndarray,
    position: np.ndarray,
    spike_times: np.ndarray,
    spike_waveform_features: np.ndarray,
    *,
    feature_order: Sequence[int] | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Mark density conditional intensity (MDCI) transform [1]_.

    Marks are transformed by the sequential CDFs of the electrode's mark
    density over the whole period, ``f(m) = Gamma(m) / integral Gamma``, where
    ``Gamma(m) = integral_0^T lambda(x(t), m) dt``, and each spike's time by the
    distribution of times given its mark:

        u_i = integral_0^{s_i} lambda(x(t), m_i) dt / Gamma(m_i).

    For spikes generated by the model the unordered points ``(u_i, v_i)`` are
    uniform on ``[0, 1]^(d+1)``. Taken in time order they are not independent,
    but these models depend on time only through position, so given their
    number the points are an independent sample and the order-invariant tests
    in this module apply. Compared with :func:`ircm_transform`, spikes with
    similar marks stay close, which targets misfit in the model of individual
    units rather than in the timing between them.

    Parameters
    ----------
    encoding_model, algorithm, electrode, position_time, position, spike_times,
    spike_waveform_features, feature_order
        As for :func:`ircm_transform`. ``position_time`` spans the period
        ``[0, T]``.

    Returns
    -------
    u : np.ndarray, shape (n_spikes,)
        Rescaled spike times.
    v : np.ndarray, shape (n_spikes, n_features)
        Column ``l`` is the CDF of feature ``feature_order[l]`` given the
        features before it, under ``f(m)``.

    Notes
    -----
    The time integrals evaluate the intensity at the interior place bins, as
    the non-local likelihood does: the position at each sample is assigned to
    its bin, and the integrand is interpolated linearly in time between
    samples. The approximation error shrinks with the bin size relative to the
    position bandwidth.
    """
    _check_algorithm(algorithm)
    time, positions, spike_times, _, marks = _prepare_inputs(
        encoding_model, position_time, position, spike_times, spike_waveform_features
    )
    model = electrode_model(encoding_model, algorithm, electrode)
    sample_bins = model.bin_indices(positions)
    total_time = _time_in_bins(time, sample_bins, model.n_bins, time[-1:])[0]
    with np.errstate(divide="ignore"):
        log_total_time = np.log(total_time)
    u = np.empty(len(spike_times))
    for first in range(0, len(spike_times), 512):
        last = min(first + 512, len(spike_times))
        log_intensity = model.log_intensity_at_bins(marks[first:last])
        with np.errstate(divide="ignore"):
            log_elapsed = np.log(
                _time_in_bins(time, sample_bins, model.n_bins, spike_times[first:last])
            ).T
        log_mass = logsumexp(log_total_time[:, None] + log_intensity, axis=0)
        if not np.all(np.isfinite(log_mass)):
            raise ValueError(
                "the fitted intensity of some spike marks is zero over the whole "
                "trajectory, so the model gives those spikes no probability"
            )
        u[first:last] = np.exp(
            logsumexp(log_elapsed + log_intensity, axis=0) - log_mass
        )
    v = model.time_integrated_mark_cdf(total_time, marks, feature_order)
    return np.clip(u, 0.0, 1.0), v


def _unit_cube_samples(samples):
    samples = np.asarray(samples, dtype=float)
    if (
        samples.ndim != 2
        or samples.shape[0] == 0
        or not np.all(np.isfinite(samples))
        or np.any((samples < 0) | (samples > 1))
    ):
        raise ValueError(
            "samples must be a nonempty (n_samples, n_dims) array in [0, 1]"
        )
    return samples


class KSUniformityResult(NamedTuple):
    """One-sample Kolmogorov-Smirnov tests of each coordinate against U(0, 1)."""

    statistic: np.ndarray
    p_value: np.ndarray


def ks_uniformity_test(samples: np.ndarray) -> KSUniformityResult:
    """Test each coordinate of transformed points for uniformity.

    Parameters
    ----------
    samples : np.ndarray, shape (n_samples, n_dims)
        Points in ``[0, 1]^n_dims``, such as ``np.column_stack((u, v))``.

    Returns
    -------
    result : KSUniformityResult
        ``statistic`` and ``p_value``, each of shape ``(n_dims,)``. Each test
        has its own p-value; compare their minimum with ``alpha / n_dims``
        (Bonferroni) to test all coordinates together. Uniform coordinates do
        not imply a jointly uniform sample; see :func:`multivariate_ks_test`.
    """
    samples = _unit_cube_samples(samples)
    tests = [scipy.stats.kstest(column, "uniform") for column in samples.T]
    return KSUniformityResult(
        np.array([test.statistic for test in tests]),
        np.array([test.pvalue for test in tests]),
    )


class ChiSquaredUniformityResult(NamedTuple):
    """Pearson chi-square test of counts in equal sub-cubes."""

    statistic: float
    p_value: float
    degrees_of_freedom: int
    n_bins_per_dim: int


def pearson_chi_squared_test(
    samples: np.ndarray, n_bins_per_dim: int | None = None
) -> ChiSquaredUniformityResult:
    """Test points for uniformity on ``[0, 1]^d`` with Pearson's chi-square.

    The cube is divided into ``M = n_bins_per_dim ** d`` equal sub-cubes, each
    expecting ``n / M`` points under uniformity, and
    ``X^2 = sum_j (r_j - n / M)^2 / (n / M)`` is compared with a chi-square
    distribution with ``M - 1`` degrees of freedom.

    Parameters
    ----------
    samples : np.ndarray, shape (n_samples, n_dims)
        Points in ``[0, 1]^n_dims``.
    n_bins_per_dim : int, optional
        Divisions per axis. By default the largest number, at least 2, that
        leaves at least five expected points per sub-cube.

    Returns
    -------
    result : ChiSquaredUniformityResult
    """
    samples = _unit_cube_samples(samples)
    n_samples, n_dims = samples.shape
    if n_bins_per_dim is None:
        n_bins_per_dim = max(2, int(np.floor((n_samples / 5.0) ** (1.0 / n_dims))))
        while n_bins_per_dim > 2 and n_samples / n_bins_per_dim**n_dims < 5.0:
            n_bins_per_dim -= 1
    if n_bins_per_dim < 1:
        raise ValueError("n_bins_per_dim must be a positive integer")
    n_cells = n_bins_per_dim**n_dims
    cell = np.minimum(np.floor(samples * n_bins_per_dim), n_bins_per_dim - 1)
    flat = np.ravel_multi_index(cell.astype(int).T, (n_bins_per_dim,) * n_dims)
    counts = np.bincount(flat, minlength=n_cells)
    expected = n_samples / n_cells
    statistic = float(np.sum((counts - expected) ** 2) / expected)
    degrees_of_freedom = n_cells - 1
    return ChiSquaredUniformityResult(
        statistic,
        float(scipy.stats.chi2.sf(statistic, degrees_of_freedom)),
        degrees_of_freedom,
        n_bins_per_dim,
    )


class MultivariateKSResult(NamedTuple):
    """Multivariate Kolmogorov-Smirnov test with a Monte Carlo p-value."""

    statistic: float
    p_value: float
    n_samples: int
    n_simulations: int


def _multivariate_ks_statistic(samples, block_size=256):
    """Largest gap between the empirical and the uniform CDF at the samples.

    Evaluated at every sample point and just below it, where the empirical
    CDF jumps (Justel, Pena and Zamar 1997; Yousefi et al. 2020, Table 2).
    """
    statistic = 0.0
    for first in range(0, len(samples), block_size):
        points = samples[first : first + block_size]
        below_or_at = np.all(samples[None] <= points[:, None], axis=2).mean(axis=1)
        below = np.all(samples[None] < points[:, None], axis=2).mean(axis=1)
        uniform = np.prod(points, axis=1)
        statistic = max(
            statistic,
            float(np.max(np.abs(below_or_at - uniform))),
            float(np.max(np.abs(below - uniform))),
        )
    return statistic


def multivariate_ks_test(
    samples: np.ndarray,
    *,
    n_simulations: int = 200,
    max_samples: int = 2000,
    rng: np.random.Generator | int | None = None,
) -> MultivariateKSResult:
    """Test points for joint uniformity with a multivariate KS statistic.

    The statistic is the largest gap between the points' empirical CDF and
    the uniform CDF ``prod_l z_l``, at the points. Its null distribution
    depends on the number of points and dimensions, so the p-value comes from
    ``n_simulations`` uniform samples of the same size. Unlike per-coordinate
    tests, it detects dependence between coordinates. It is invariant to the
    order of the points, so it also applies to the exchangeable MDCI points.

    Parameters
    ----------
    samples : np.ndarray, shape (n_samples, n_dims)
        Points in ``[0, 1]^n_dims``.
    n_simulations : int, optional
        Uniform samples drawn for the Monte Carlo p-value. Default 200.
    max_samples : int, optional
        Larger inputs are subsampled without replacement to this many points;
        the statistic costs ``O(n_samples ** 2 * n_dims)``. Default 2000.
    rng : numpy.random.Generator or int, optional
        Source of the subsample and the simulations.

    Returns
    -------
    result : MultivariateKSResult
        ``p_value = (1 + #{simulated >= observed}) / (1 + n_simulations)``.
    """
    samples = _unit_cube_samples(samples)
    if n_simulations < 1 or max_samples < 1:
        raise ValueError("n_simulations and max_samples must be positive")
    rng = np.random.default_rng(rng)
    if len(samples) > max_samples:
        samples = samples[rng.choice(len(samples), max_samples, replace=False)]
    statistic = _multivariate_ks_statistic(samples)
    simulated = np.array(
        [
            _multivariate_ks_statistic(rng.uniform(size=samples.shape))
            for _ in range(n_simulations)
        ]
    )
    p_value = (1 + np.count_nonzero(simulated >= statistic)) / (1 + n_simulations)
    return MultivariateKSResult(statistic, float(p_value), len(samples), n_simulations)
