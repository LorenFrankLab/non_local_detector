"""Goodness of fit for clusterless (marked point process) likelihood models [1]_.

``ircm_transform`` and ``mdci_transform`` map one electrode's spike times and
waveform marks to points in ``[0, 1]^(d+1)`` using a fitted clusterless
encoding model. For spikes generated by that model the points are uniform, so
``ks_uniformity_test``, ``pearson_chi_squared_test`` and
``multivariate_ks_test`` test the fit. Apply them to held-out data: a model
evaluated on the spikes it was fitted to looks better than it is.

Adapted from https://github.com/YousefiLab/Marked-PointProcess-Goodness-of-Fit.

References
----------
.. [1] Yousefi, A., Amidi, Y., Nazari, B., and Eden, U. T. (2020). Assessing
   goodness-of-fit in marked point process models of neural population coding
   via time and rate rescaling. Neural Computation 32, 2145-2186.
   https://doi.org/10.1162/neco_a_01321
"""

